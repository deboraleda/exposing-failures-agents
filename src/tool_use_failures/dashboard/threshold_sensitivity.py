# threshold_sensitivity.py
#
# Corrupt-success rate per judge for several DeepEval thresholds, written as a
# pgfplots line chart for the paper. Reads data/runs.json, so rebuild the
# dashboard first.
#
# Usage (from src/):
#   python -m tool_use_failures.dashboard.threshold_sensitivity

import json
import os

THRESHOLDS = [0.5, 0.6, 0.7, 0.8, 0.9, 1.0]
USED_THRESHOLD = 0.7

HERE = os.path.dirname(os.path.abspath(__file__))
RUNS_FILE = os.path.join(HERE, "data", "runs.json")
OUTPUT_FILE = os.path.join(HERE, "data", "threshold_sensitivity.tex")

STYLES = ["color=cJudgeA, mark=*", "color=cJudgeB, mark=square*"]


def main():
    rows = [r for r in json.load(open(RUNS_FILE, encoding="utf-8"))["rows"] if r["judge_score"] is not None]

    series = {}
    for judge in sorted({r["judge_label"] for r in rows}):
        failed = [r for r in rows if r["judge_label"] == judge and not r["det_pass"]]
        series[judge] = [
            (t, 100 * sum(r["judge_score"] >= t for r in failed) / len(failed))
            for t in THRESHOLDS
        ]

    for judge, points in series.items():
        print(judge, " ".join(f"{t:.1f}={v:.1f}%" for t, v in points))

    plots = []
    for (judge, points), style in zip(series.items(), STYLES):
        coords = " ".join(f"({t:.1f},{v:.1f})" for t, v in points)
        plots.append(
            f"\\addplot[{style}, thick, mark size=1.8pt] coordinates {{{coords}}};\n"
            f"\\addlegendentry{{{judge.split('/')[-1]}}}"
        )

    tex = f"""% Generated by threshold_sensitivity.py -- do not edit by hand.
% Preamble: \\usepackage{{pgfplots}} \\pgfplotsset{{compat=1.18}}
% \\definecolor{{cJudgeA}}{{HTML}}{{4338CA}} \\definecolor{{cJudgeB}}{{HTML}}{{D97706}}
\\begin{{tikzpicture}}
\\begin{{axis}}[
  width=\\linewidth, height=5.2cm,
  xlabel={{DeepEval threshold}}, ylabel={{Corrupt success rate (\\%)}},
  xmin=0.45, xmax=1.05, ymin=0, ymax=60,
  xtick={{{",".join(f"{t:.1f}" for t in THRESHOLDS)}}},
  xticklabel style={{/pgf/number format/fixed, /pgf/number format/precision=1}},
  ymajorgrids, grid style={{gray!20}},
  legend pos=north east, legend style={{font=\\footnotesize, draw=none, fill=none}},
  tick label style={{font=\\footnotesize}}, label style={{font=\\footnotesize}},
]
\\draw[gray!60, dashed] (axis cs:{USED_THRESHOLD},0) -- (axis cs:{USED_THRESHOLD},60)
  node[pos=0.97, right, font=\\scriptsize, text=gray] {{used}};
{chr(10).join(plots)}
\\end{{axis}}
\\end{{tikzpicture}}
"""

    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        f.write(tex)

    print(f"Saved → {OUTPUT_FILE}")


if __name__ == "__main__":
    main()
